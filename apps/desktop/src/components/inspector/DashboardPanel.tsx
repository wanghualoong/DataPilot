/** Fine-grained rows for every dataset of a spec (never aggregated or sampled here). */
async function hydrate(id: string, spec: any) {
  const data: Record<string, any> = {};
  const errors: string[] = [];
  await Promise.all(Object.keys(spec.datasets ?? {}).map(async (k) => {
    try { data[k] = await core.request("dashboard/query", { session: sid(), id, dataset: k, inline: true }); }
    catch (e) { errors.push(`${k}: ${(e as Error).message}`); }
  }));
  return { data, errors };
}

/** Offline HTML: the same renderer + ECharts inlined (like the SwiftUI export). */
async function standaloneHTML(spec: any, data: any, dark: boolean) {
  const read = async (p: string) => (await fetch("/web/" + p)).text();
  const safe = (s: string) => s.replace(/<\/script/gi, "<\\/script");
  const [css, ec, host, expr, dash] = await Promise.all(["dashboard.css", "vendor/echarts.min.js", "host.js", "expr.js", "dashboard.js"].map(read));
  const lang = L("zh", "en");
  return `<!doctype html><html lang="${lang}"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>${(spec.title ?? "Dashboard").replace(/</g, "&lt;")}</title><style>${css}</style><script>${safe(ec)}</script></head>
<body><div id="root"></div><script>${safe(host)}</script><script>${safe(expr)}</script><script>${safe(dash)}</script>
<script>DP.setPalette(${safe(JSON.stringify(useApp.getState().config?.settings?.dashboardPalette ?? "default"))});DP.setLang('${lang}');DP.setTheme('${dark ? "dark" : "light"}');DP.renderDashboard(${safe(JSON.stringify(spec))}, ${safe(JSON.stringify(data))}, {standalone:true});</script>
<p style="color:#898781;font:11px system-ui;padding:0 16px 16px">Generated by DataPilot · ${new Date().toLocaleString()}</p></body></html>`;
}

/** No dashboard yet: this session's inline charts with one-click pinning (port of the Swift SessionChartsList). */
function SessionCharts() {
  const st = useApp();
  const chat = st.selected ? st.chats[st.selected] : undefined;
  const charts = (chat?.items ?? []).filter((i: any) => i.kind === "tool" && i.display?.kind === "chart" && i.display?.sql) as any[];
  if (!charts.length) return <div className="muted small pad">{L("在聊天中说“做一个销售看板，可按地区和品类筛选”，或输入 /dashboard", "Ask “build a sales dashboard filterable by region and category”, or type /dashboard")}</div>;
  // same as Swift pinAllCharts: a chart that cannot be pinned is skipped, the rest still go in
  const pinAll = async () => {
    const { id, failed } = await pinCharts(charts, async (c) =>
      (await core.request("dashboard/pin", { session: sid(), chart: c.display, title: L("本会话看板", "Session dashboard") })).id);
    useApp.setState((s) => ({ dataVersion: s.dataVersion + 1 }));
    if (id) st.openInspector("dashboards", id);
    if (failed) st.note(L(`有 ${failed} 张图表没能加入看板，已跳过`, `${failed} chart(s) could not be added and were skipped`));
  };
  return (
    <div className="pad dcharts">
      <b>{L("本会话图表", "Charts in this session")}</b>
      <div className="muted small">{L(`已生成 ${charts.length} 张图表，可直接组成看板：`, `${charts.length} charts so far — turn them into a dashboard:`)}</div>
      <div className="dclist">
        {charts.map((c) => (
          <div key={c.id} className="irow">
            <ChartColumn size={13} className="muted" /><span className="grow ell">{c.display?.spec?.title || c.summary || c.tool_name}</span>
            <IconBtn icon={Pin} size={13} title={L("加入看板", "Add to dashboard")} onClick={async () => { await pinChart(c.display); useApp.setState((s) => ({ dataVersion: s.dataVersion + 1 })); }} />
          </div>
        ))}
      </div>
      <div className="row">
        <button className="primary" onClick={pinAll}><LayoutDashboard size={13} />{L("一键生成看板", "Build dashboard from all")}</button>
        <button disabled={!!chat?.running} onClick={() => st.send(dashboardPrompt)}><Sparkles size={13} />{L("让 Agent 设计看板", "Let the agent design one")}</button>
      </div>
    </div>
  );
}

export function DashboardPanel() {
  const st = useApp();
  const session = st.sessions.find((s) => s.id === st.selected);
  const inProject = !!session?.project_id;
  const [showAll, setShowAll] = useState(false);
  const [list] = useLoad(async () => (await core.request("dashboard/list", { session: sid() })).dashboards as any[]);
  const visible = (list ?? []).flatMap((e) => {
    if (!inProject || e.owner === st.selected) return [{ id: e.id, title: e.title }];
    if (e.owner == null) return [{ id: e.id, title: e.title + L(" · 项目共享", " · shared") }];
    return showAll ? [{ id: e.id, title: e.title + L(" · 其他对话", " · other chat") }] : [];
  });
  const wanted = st.inspector?.id && visible.some((v) => v.id === st.inspector!.id) ? st.inspector.id : visible[0]?.id;
  const [loaded, err, reload, busy] = useLoad(async () => {
    if (!wanted) return null;
    const spec = (await core.request("dashboard/get", { session: sid(), id: wanted })).spec;
    return { id: wanted, spec, ...(await hydrate(wanted, spec)) };
  }, [wanted]);
  const render = useCallback((w: any) => { if (loaded) w.DP?.renderDashboard(loaded.spec, loaded.data, { keepState: true }); }, [loaded]);
  const onMessage = useCallback(async (m: any, w: any) => {
    if (!loaded) return;
    const name = loaded.spec.title || "dashboard";
    if (m.type === "exportCSV") saveText(m.name || "data", "csv", m.csv || "", true);
    else if (m.type === "widgetEdit") await core.request("dashboard/patch", { session: sid(), id: loaded.id, widget: m.widget, patch: m.patch }).catch(st.fail);
    else if (m.type === "export" && m.format === "png") { const u = await w.DP?.exportPNG(); if (u) saveBase64(name, "png", u.split(",")[1]); }
    else if (m.type === "export") saveText(name, "html", await standaloneHTML(loaded.spec, loaded.data, resolvedTheme() === "dark"));
  }, [loaded]);
  const customPal = useApp((x) => x.config?.settings?.dashboardPalette);
  const setPalette = async (pal: string | string[] | null) => {
    if (!loaded) return;
    const spec = { ...loaded.spec };
    if (pal) spec.palette = pal; else delete spec.palette;
    try { await core.request("dashboard/save", { session: sid(), id: loaded.id, spec }); reload(); } catch (e) { st.fail(e); }
  };
  const sets = Object.entries(loaded?.spec?.datasets ?? {}).filter(([, v]: any) => v?.sql) as [string, any][];
  return (
    <div className="ipanel fill">
      <div className="row pad">
        <select className="grow" value={wanted ?? ""} onChange={(e) => st.openInspector("dashboards", e.target.value)}>
          {!visible.length && <option value="">{L("还没有看板", "No dashboards yet")}</option>}
          {visible.map((v) => <option key={v.id} value={v.id}>{v.title}</option>)}
        </select>
        {inProject && <label className="small"><input type="checkbox" checked={showAll} onChange={(e) => setShowAll(e.target.checked)} /> {L("全部", "All")}</label>}
        <IconBtn icon={RefreshCw} size={13} title={L("重新查询数据", "Re-query data")} spin={busy} onClick={reload} />
        {loaded && (
          <Popover align="right" caret={false} title={L("看板配色（只影响这个看板）", "Colours of this dashboard")} label={<Palette size={14} />}>
            <MenuItem checked={!loaded.spec.palette} onClick={() => setPalette(null)}>{L("跟随设置（默认配色）", "Follow settings")}</MenuItem>
            <MenuSep />
            {PALETTE_NAMES.map(([k, label, c]) => (
              <MenuItem key={k} checked={loaded.spec.palette === k} onClick={() => setPalette(k)}><span className="row">{label}<Swatch colors={c} /></span></MenuItem>
            ))}
            <MenuSep />
            {Array.isArray(loaded.spec.palette) && (
              <MenuItem checked><span className="row">{L("本看板的自定义配色", "This dashboard's custom colours")}<Swatch colors={swatches(loaded.spec.palette)} /></span></MenuItem>
            )}
            {Array.isArray(customPal) && JSON.stringify(customPal) !== JSON.stringify(loaded.spec.palette) && (
              <MenuItem onClick={() => setPalette(customPal as string[])}><span className="row">{L("使用设置里的自定义配色", "Use custom colours from Settings")}<Swatch colors={swatches(customPal)} /></span></MenuItem>
            )}
            <MenuItem onClick={() => st.openSettings("general")}>{L("编辑自定义配色…", "Edit custom colours…")}</MenuItem>
          </Popover>
        )}
        {loaded && (
          <Menu label={L("导出…", "Export…")} items={[
            [L("HTML（离线可交互）", "HTML (offline, interactive)"), async () => saveText(loaded.spec.title || "dashboard", "html", await standaloneHTML(loaded.spec, loaded.data, resolvedTheme() === "dark"))],
            [L("规格 JSON", "Spec JSON"), () => saveText(loaded.spec.title || "dashboard", "json", JSON.stringify(loaded.spec, null, 2))],
            ...sets.flatMap(([k, v]) => ["csv", "xlsx"].map((f) => [L(`数据集「${k}」明细 `, `Dataset “${k}” rows `) + f.toUpperCase(),
              () => exportTo({ sql: v.sql, format: f, filename: `${loaded.spec.title || "dashboard"}_${k}` })] as [string, () => void])),
          ]} />
        )}
      </div>
      {err && <KernelError raw={err} reload={reload} className="pad" />}
      {loaded?.errors?.length ? <div className="notice err small pad">{loaded.errors.join("\n")}</div> : null}
      {loaded ? <WebFrame render={render} onMessage={onMessage} height="100%" />
        : !wanted && list ? <SessionCharts /> : null}
    </div>
  );
}
