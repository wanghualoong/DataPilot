// protocol/*.schema.json → src/protocol/*.ts (types are generated, never hand-written)
import { compileFromFile } from "json-schema-to-typescript";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
const here = dirname(fileURLToPath(import.meta.url));
const proto = join(here, "../../../protocol");
const out = join(here, "../src/protocol");
const banner = "/* Generated by scripts/gen-protocol.mjs from protocol/*.schema.json — do not edit. */";
for (const [schema, file] of [["agent-event.schema.json", "agent-event.ts"], ["rpc.schema.json", "rpc.ts"]]) {
  const ts = await compileFromFile(join(proto, schema), { bannerComment: banner, cwd: proto, additionalProperties: false, strictIndexSignatures: false });
  writeFileSync(join(out, file), ts);
  console.log("wrote", file);
}
